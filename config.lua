_G._U = function(str, ...)
    if not _G.Locales then return "Locales Not Loaded: " .. str end
    local lang = (Config and Config.Language) or 'ar'
    if _G.Locales[lang] and _G.Locales[lang][str] then
        local text = _G.Locales[lang][str]
        local args = {...}
        if #args > 0 then
            return string.format(text, table.unpack(args))
        end
        return text
    else
        return "Label missing: " .. str
    end
end
_G.U = _G._U
